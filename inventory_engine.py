class ChamundaInventoryManager:
    """Enterprise inventory manager for Chamunda Automobile Parts & Service."""

    def __init__(self, data_dir: Path = DATA_DIR):
        self.data_dir = data_dir
        self.data_dir.mkdir(parents=True, exist_ok=True)
        self.parts_file = self.data_dir / "re_parts_catalog.json"
        self._initialize_catalog()

    def _initialize_catalog(self) -> None:
        if not self.parts_file.exists():
            self.parts_file.write_text(json.dumps(DEFAULT_PARTS, indent=2), encoding="utf-8")

    def get_all_parts(self) -> List[Dict[str, Any]]:
        """Retrieve all parts in catalog."""
        try:
            return json.loads(self.parts_file.read_text(encoding="utf-8") or "[]")
        except Exception:
            return DEFAULT_PARTS

    def search_parts(self, query: str) -> List[Dict[str, Any]]:
        """Search parts by name, model, category, or OEM number."""
        return self.filter_parts(query=query)

    def filter_parts(
        self,
        query: str = "",
        part_number: str = "",
        model: str = "",
        category: str = "",
        min_price: Optional[float] = None,
        max_price: Optional[float] = None,
        min_cost: Optional[float] = None,
        max_cost: Optional[float] = None,
        stock_status: str = "all",
        min_stock: Optional[int] = None,
        max_stock: Optional[int] = None,
        bin_location: str = "",
        hsn_code: str = "",
        unit: str = "",
        sort_by: str = "name",
        limit: Optional[int] = None,
        offset: int = 0,
    ) -> List[Dict[str, Any]]:
        """
        Comprehensive multi-parameter filter and search engine for Royal Enfield parts catalog.

        Supports filtering by ANY available data attribute:
        - Free text / multi-token keyword search
        - OEM Part number / SKU
        - Motorcycle model compatibility
        - Part category
        - Price range (min_price, max_price)
        - Cost range (min_cost, max_cost)
        - Stock status (in_stock, low_stock, out_of_stock)
        - Stock quantity range (min_stock, max_stock)
        - Warehouse bin location
        - GST HSN code
        - Unit of measurement
        - Flexible sorting and pagination
        """
        parts = self.get_all_parts()
        filtered = []

        q = (query or "").strip().lower()
        pn = (part_number or "").strip().lower()
        mod = (model or "").strip().lower()
        cat = (category or "").strip().lower()
        status = (stock_status or "all").strip().lower()
        bin_loc = (bin_location or "").strip().lower()
        hsn = (hsn_code or "").strip().lower()
        u_unit = (unit or "").strip().lower()

        for p in parts:
            # 1. Query filter (multi-token search across all fields with plural stemming)
            if q:
                full_text = f"{p.get('name', '')} {p.get('description', '')} {p.get('category', '')} {p.get('part_number', '')} {p.get('oem_number', '')} {' '.join(p.get('models', []))} {p.get('bin_location', '')} {p.get('hsn_code', '')}".lower()
                if q not in full_text:
                    terms = [t for t in q.split() if len(t) > 0]
                    if not all(t in full_text or (len(t) > 3 and t.rstrip('s') in full_text) for t in terms):
                        continue

            # 2. Part number / OEM number filter
            if pn:
                match_pn = pn in p.get("part_number", "").lower()
                match_oem = pn in p.get("oem_number", "").lower()
                match_pid = pn in p.get("part_id", "").lower()
                if not (match_pn or match_oem or match_pid):
                    continue

            # 3. Model filter
            if mod:
                if not any(mod in m.lower() for m in p.get("models", [])):
                    continue

            # 4. Category filter
            if cat:
                if cat not in p.get("category", "").lower():
                    continue

            # 5. Price range filter (MRP)
            mrp = float(p.get("mrp", 0))
            if min_price is not None and mrp < float(min_price):
                continue
            if max_price is not None and mrp > float(max_price):
                continue

            # 5b. Wholesale cost filter
            cost = float(p.get("cost_price", 0))
            if min_cost is not None and cost < float(min_cost):
                continue
            if max_cost is not None and cost > float(max_cost):
                continue

            # 6. Stock status filter
            stock = int(p.get("stock", 0))
            min_thresh = int(p.get("min_threshold", 5))
            if status == "in_stock" and stock <= 0:
                continue
            elif status == "low_stock" and (stock > min_thresh or stock == 0):
                continue
            elif status == "out_of_stock" and stock > 0:
                continue

            # 6b. Stock quantity bounds
            if min_stock is not None and stock < int(min_stock):
                continue
            if max_stock is not None and stock > int(max_stock):
                continue

            # 7. Warehouse Bin location filter
            if bin_loc and bin_loc not in p.get("bin_location", "").lower():
                continue

            # 8. GST HSN code filter
            if hsn and hsn not in p.get("hsn_code", "").lower():
                continue

            # 9. Unit filter
            if u_unit and u_unit not in p.get("unit", "").lower():
                continue

            filtered.append(p)

        # 10. Multi-field Sorting
        s_by = (sort_by or "name").strip().lower()
        if s_by in ("price_asc", "mrp_asc", "price"):
            filtered.sort(key=lambda x: float(x.get("mrp", 0)))
        elif s_by in ("price_desc", "mrp_desc"):
            filtered.sort(key=lambda x: float(x.get("mrp", 0)), reverse=True)
        elif s_by in ("cost_asc",):
            filtered.sort(key=lambda x: float(x.get("cost_price", 0)))
        elif s_by in ("cost_desc",):
            filtered.sort(key=lambda x: float(x.get("cost_price", 0)), reverse=True)
        elif s_by in ("stock", "stock_desc"):
            filtered.sort(key=lambda x: int(x.get("stock", 0)), reverse=True)
        elif s_by in ("stock_asc",):
            filtered.sort(key=lambda x: int(x.get("stock", 0)))
        elif s_by in ("part_number", "part_no", "oem"):
            filtered.sort(key=lambda x: str(x.get("part_number", x.get("oem_number", ""))).lower())
        else:  # default: name
            filtered.sort(key=lambda x: str(x.get("name", "")).lower())

        # 11. Pagination
        if offset > 0:
            filtered = filtered[offset:]
        if limit is not None and limit > 0:
            filtered = filtered[:limit]

        return filtered

    def get_filter_analytics(self, parts: List[Dict[str, Any]]) -> Dict[str, Any]:
        """Generate comprehensive analytics and inventory valuation for filtered parts."""
        if not parts:
            return {
                "count": 0,
                "total_units": 0,
                "mrp_valuation_inr": 0,
                "cost_valuation_inr": 0,
                "gross_margin_inr": 0,
                "categories": {},
                "models": {},
            }
        total_units = sum(p.get("stock", 0) for p in parts)
        mrp_val = sum(p.get("stock", 0) * p.get("mrp", 0) for p in parts)
        cost_val = sum(p.get("stock", 0) * p.get("cost_price", 0) for p in parts)
        categories = {}
        for p in parts:
            cat = p.get("category", "Other")
            categories[cat] = categories.get(cat, 0) + 1
        return {
            "count": len(parts),
            "total_units": total_units,
            "mrp_valuation_inr": mrp_val,
            "cost_valuation_inr": cost_val,
            "gross_margin_inr": mrp_val - cost_val,
            "categories": categories,
        }

    def update_stock(self, part_id: str, quantity_delta: int) -> Optional[Dict[str, Any]]:
        """Deduct or add stock for a part."""
        parts = self.get_all_parts()
        for p in parts:
            if p["part_id"] == part_id or part_id.lower() in p["name"].lower():
                p["stock"] = max(0, p["stock"] + quantity_delta)
                self.parts_file.write_text(json.dumps(parts, indent=2), encoding="utf-8")
                return p
        return None

    def get_low_stock_alerts(self) -> List[Dict[str, Any]]:
        """Get parts running below minimum reorder threshold."""
        parts = self.get_all_parts()
        return [p for p in parts if p["stock"] <= p.get("min_threshold", 5)]

    def get_total_inventory_valuation(self) -> Dict[str, Any]:
        """Calculate total inventory cost and retail valuation."""
        parts = self.get_all_parts()
        total_items = sum(p["stock"] for p in parts)
        cost_val = sum(p["stock"] * p["cost_price"] for p in parts)
        mrp_val = sum(p["stock"] * p["mrp"] for p in parts)
        return {
            "total_distinct_skus": len(parts),
            "total_units_in_stock": total_items,
            "cost_valuation_inr": cost_val,
            "mrp_valuation_inr": mrp_val,
            "expected_gross_profit_inr": mrp_val - cost_val,
        }
